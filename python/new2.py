# Τυπώνει τους πρώτους 1000 πρώτους αριθμούς

πλήθος = 0      # πόσους πρώτους έχουμε βρει μέχρι τώρα
n = 2           # ο αριθμός που ελέγχουμε

while πλήθος < 1000:
    # Ελέγχουμε αν ο n έχει κάποιον διαιρέτη d με d*d <= n
    πρώτος = True
    d = 2
    while d * d <= n:
        if n % d == 0:
            πρώτος = False
            break
        d = d + 1

    if πρώτος:
        print(n, end=" ")
        πλήθος = πλήθος + 1

    n = n + 1

print()
