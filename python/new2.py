# Ὑπολογίζει τοὺς πρώτους 1000 πρώτους ἀριθμούς

πρῶτοι = []     # ἐδῶ μαζεύουμε τοὺς πρώτους ποὺ βρίσκουμε
n = 2           # ὁ ἀριθμὸς ποὺ ἐλέγχουμε

while len(πρῶτοι) < 1000:
    # Ἐλέγχουμε ἂν ὁ n ἔχει κάποιον διαιρέτη d μὲ d*d <= n
    πρῶτος = True
    d = 2
    while d * d <= n:
        if n % d == 0:
            πρῶτος = False
            break
        d = d + 1

    if πρῶτος:
        πρῶτοι.append(n)

    n = n + 1

print(πρῶτοι)
print("Ὁ 1000ὸς πρῶτος εἶναι ὁ", πρῶτοι[-1])
