# fact.py -- παραγοντικό με βρόχο for
# Υπολογίζει το n! = 1 · 2 · 3 · ... · n.

# Διαβάζουμε τον ακέραιο n από τον χρήστη.
n = int(input('Δώσε έναν ακέραιο: '))

# Το f κρατά το γινόμενο που έχει υπολογιστεί ως τώρα.
# Αρχική τιμή 1, το ουδέτερο στοιχείο του πολλαπλασιασμού,
# οπότε για n = 0 προκύπτει σωστά 0! = 1.
f = 1

# Πολλαπλασιάζουμε το f διαδοχικά με 1, 2, ..., n.
# Μετά το βήμα i ισχύει f = i!.
for i in range(1, n + 1):
    f *= i          # συντομογραφία του f = f * i

# Εκτύπωση του αποτελέσματος.
print('Το παραγοντικό του', n, 'είναι το', f)
