# Έλεγχος αν ένας ακέραιος είναι πρώτος, με δοκιμαστικές διαιρέσεις.

# Διαβάζουμε από τον χρήστη έναν αριθμό (ως κείμενο) και τον
# μετατρέπουμε σε ακέραιο.
z = int(input("Δῶσε μου ἕναν ἀριθμό: "))

# Υποθέτουμε αρχικά ότι ο z είναι πρώτος, μέχρι να βρεθεί διαιρέτης.
isprime = True

# Δοκιμάζουμε κάθε πιθανό διαιρέτη i από το 2 έως το z-1.
for i in range(2, z):
    # Αν το i διαιρεί ακριβώς τον z (μηδενικό υπόλοιπο),
    # τότε ο z έχει γνήσιο διαιρέτη και δεν είναι πρώτος.
    if z % i == 0:
        isprime = False

# Επιλέγουμε τη λέξη άρνησης ανάλογα με το αποτέλεσμα
# (υπό συνθήκη έκφραση: τιμή_αν_αληθές if συνθήκη else τιμή_αν_ψευδές).
x = '' if isprime else 'δεν'

# Εκτύπωση του αποτελέσματος.
print('Ὀ ἀριθμὸς', z, x, 'εἶναι πρώτος')
