# Έλεγχος αν κάθε αριθμός σε ένα διάστημα είναι πρώτος.
# Εξετάζουμε τους ακεραίους από 1.000.000 έως 1.099.999
# (το range δεν περιλαμβάνει το άνω άκρο).

for z in range(1_000_000, 1_100_000):
    # Για κάθε z υποθέτουμε αρχικά ότι είναι πρώτος.
    isprime = True

    if z % 2 == 0:
        # Ο z είναι άρτιος και μεγαλύτερος του 2, άρα δεν είναι πρώτος.
        # Τυπώνουμε not isprime, δηλαδή False.
        print(z, not isprime)
    else:
        # Ο z είναι περιττός: δοκιμάζουμε μόνο περιττούς διαιρέτες
        # i = 3, 5, 7, ..., έως z // 2. Κανένας γνήσιος διαιρέτης
        # δεν υπερβαίνει το z/2.
        for i in range(3, z // 2 + 1, 2):
            if z % i == 0:
                # Βρέθηκε διαιρέτης: ο z δεν είναι πρώτος.
                isprime = False
        # Τυπώνουμε τον αριθμό και το αποτέλεσμα (True ή False).
        print(z, isprime)
