import math
import matplotlib.pyplot as plt

# Βρίσκουμε τους πρώτους έως n και σχεδιάζουμε
# τη γραφική παράσταση «α/α πρώτου → πρώτος».

n = 40000
y = [2]                          # το 2 είναι ο μόνος άρτιος πρώτος

# Εξετάζουμε τους περιττούς c = 3, 5, ..., n.
for c in range(3, n + 1, 2):
    flag = 1                     # σημαία: 1 = «πρώτος», 0 = «σύνθετος»

    # Δοκιμαστικές διαιρέσεις μόνο με περιττούς k = 3, 5, ..., ⌊√c⌋,
    # αφού ο c είναι περιττός.
    for k in range(3, math.isqrt(c) + 1, 2):
        if c % k == 0:
            flag = 0             # βρέθηκε διαιρέτης
            break                # δεν χρειάζεται να συνεχίσουμε

    if flag:
        y.append(c)              # ο c είναι πρώτος· τον κρατάμε

# Οι τετμημένες: ο αύξων αριθμός κάθε πρώτου (1, 2, ..., l),
# ώστε y[i-1] να είναι ο i-οστός πρώτος.
l = len(y)
x = list(range(1, l + 1))
print(f'Πλήθος πρώτων ≤ {n}: {l}')

# Γραφική παράσταση: στο σημείο i ο i-οστός πρώτος.
plt.plot(x, y)
plt.show()
