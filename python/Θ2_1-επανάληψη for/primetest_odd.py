# Έλεγχος αν ένας ακέραιος είναι πρώτος. Βελτίωση της προηγούμενης
# εκδοχής: χειριζόμαστε χωριστά το 2 και τους άρτιους, και
# δοκιμάζουμε μόνο περιττούς διαιρέτες.

# Διαβάζουμε τον αριθμό από τον χρήστη και τον μετατρέπουμε σε ακέραιο.
z = int(input("Δῶσε μου ἕναν ἀριθμό: "))

# Υποθέτουμε αρχικά ότι ο z είναι πρώτος.
isprime = True

# Το 2 είναι πρώτος, άρα δεν χρειάζεται κανένας έλεγχος.
if z != 2:
    if z % 2 != 0:
        # Ο z είναι περιττός, άρα δεν έχει άρτιους διαιρέτες.
        # Δοκιμάζουμε μόνο τους περιττούς i = 3, 5, 7, ..., < z.
        for i in range(3, z, 2):
            if z % i == 0:
                # Βρέθηκε γνήσιος διαιρέτης: ο z δεν είναι πρώτος.
                isprime = False
    else:
        # Ο z είναι άρτιος και διάφορος του 2,
        # άρα διαιρείται από το 2 και δεν είναι πρώτος.
        isprime = False

# Εκτύπωση του αποτελέσματος (True ή False).
print(isprime)
