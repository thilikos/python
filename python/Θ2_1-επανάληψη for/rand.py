import random

import matplotlib.pyplot as plt

# Νέφος 10000 σημείων με κανονική κατανομή στις δύο συντεταγμένες.
# Οι συντεταγμένες x και y είναι ανεξάρτητες, άρα το νέφος είναι
# κυκλικά συμμετρικό γύρω από το κέντρο του.

x = []      # οι τετμημένες των σημείων
y = []      # οι τεταγμένες των σημείων
for i in range(100000):
    # random.normalvariate(1, 1): κανονική κατανομή με μέση τιμή 1
    # και τυπική απόκλιση 1. Ο πολλαπλασιασμός επί 100 δίνει
    # κανονική κατανομή με μέση τιμή 100 και τυπική απόκλιση 100.
    x.append(100 * random.normalvariate(1, .1))
    y.append(100 * random.normalvariate(1, .1))

# Εκτύπωση των δύο λιστών και του πλήθους των σημείων
# (προσοχή: τυπώνονται 20000 αριθμοί)
print(x, y, len(x))

# Σχεδίαση: κάθε σημείο (x[i], y[i]) ως τελεία, χωρίς γραμμές
plt.plot(x, y, ".")
plt.show()
