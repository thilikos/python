# Έλεγχος αν ένας ακέραιος είναι πρώτος, με δοκιμαστικές διαιρέσεις.

# Διαβάζουμε από τον χρήστη έναν αριθμό (ως κείμενο) και τον
# μετατρέπουμε σε ακέραιο.
