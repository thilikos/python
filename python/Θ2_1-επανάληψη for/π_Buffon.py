import math, random

# Προσομοίωση του προβλήματος της βελόνας του Buffon:
# ρίχνουμε τυχαία μια βελόνα μήκους 1 σε επίπεδο με παράλληλες
# οριζόντιες ευθείες σε απόσταση 1 (τις ευθείες y = ακέραιος).
# Η πιθανότητα η βελόνα να τέμνει κάποια ευθεία είναι 2/π,
# οπότε από τη σχετική συχνότητα τομών εκτιμούμε το π.

drops = 1000000
# φορὲς ῥίψης
success = 0      # πλήθος ρίψεων στις οποίες η βελόνα τέμνει ευθεία

for i in range(1, drops + 1):
    # Το ύψος του ενός άκρου της βελόνας, ομοιόμορφα στο [0, 1).
    # Λόγω περιοδικότητας αρκεί να εξετάσουμε μία μόνο λωρίδα.
    y = random.random()

    # Η γωνία της βελόνας ως προς τις ευθείες, ομοιόμορφα στο [0, 2π).
    a = random.random() * 2 * math.pi

    # Το ύψος του άλλου άκρου (η βελόνα έχει μήκος 1).
    # Μας ενδιαφέρει μόνο η κατακόρυφη συνιστώσα sin(a).
    y1 = y + math.sin(a)

    # Η βελόνα τέμνει ευθεία ακριβώς όταν υπάρχει ακέραιος στο
    # διάστημα [min(y, y1), max(y, y1)]. Αφού το διάστημα έχει μήκος
    # το πολύ 1, αυτό ισοδυναμεί με floor(max) == ceil(min).
    # Η Python μετατρέπει το True/False σε 1/0 κατά την πρόσθεση.
    success = success + (math.floor(max(y, y1)) == math.ceil(min(y, y1)))

# Από success/drops ≈ 2/π προκύπτει π ≈ 2·drops/success.
mypi = 2*drops / success

print(f'mypi = {mypi}')        # η εκτίμηση του π
print(f'pi = {math.pi}')       # η πραγματική τιμή
print(f'{math.pi - mypi}')     # το σφάλμα της εκτίμησης
