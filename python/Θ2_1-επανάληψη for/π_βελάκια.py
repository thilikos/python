import random

# Προσέγγιση του π με τη μέθοδο Monte Carlo:
# ρίχνουμε n βελάκια στο τετράγωνο [-1, 1] x [-1, 1] και μετράμε
# πόσα πέφτουν μέσα στον εγγεγραμμένο κύκλο ακτίνας 1.
# Ο λόγος των εμβαδών κύκλου και τετραγώνου είναι π·1² / 2² = π/4,
# άρα η πιθανότητα ένα βελάκι να πέσει στον κύκλο είναι π/4.

n = 1000000      # πλήθος ρίψεων
hits = 0         # πλήθος επιτυχιών (βελάκια μέσα στον κύκλο)
for i in range(n):
    # ρίχνω το βελάκι i: τυχαίο σημείο (x, y), ομοιόμορφα στο τετράγωνο
    x = random.uniform(-1, 1)
    y = random.uniform(-1, 1)
    # ελέγχω αν είναι επιτυχία: το σημείο απέχει από το (0, 0)
    # απόσταση το πολύ 1 (συγκρίνουμε τετράγωνα, χωρίς ρίζα)
    if x**2 + y**2 <= 1:
        hits += 1

# Η σχετική συχνότητα hits/n προσεγγίζει το π/4,
# οπότε το 4·hits/n προσεγγίζει το π.
my_pi = 4 * hits / n
print(my_pi)
