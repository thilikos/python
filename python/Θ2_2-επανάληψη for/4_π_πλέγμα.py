import math

# Προσέγγιση του π με μέτρηση σημείων πλέγματος (ακέραιων σημείων)
# μέσα σε κύκλο ακτίνας w με κέντρο την αρχή των αξόνων.
# Μετράμε τα σημεία (k, j) με k, j ≥ 1 και k² + j² ≤ w²,
# δηλαδή τα σημεία του πρώτου τεταρτημορίου εκτός των αξόνων.

w = int(input('Ἀκτίνα κύκλου: '))

n1 = 0                           # πλήθος σημείων στο πρώτο τεταρτημόριο
for k in range(1, w + 1):
    # Για σταθερή τετμημένη k, οι επιτρεπτές τεταγμένες j ≥ 1 είναι
    # αυτές με j ≤ √(w² - k²), δηλαδή m = ⌊√(w² - k²)⌋ το πλήθος.
    m = math.floor(math.sqrt(w**2 - k**2))
    n1 = n1 + m

# Κάθε σημείο (k, j) είναι η πάνω δεξιά κορυφή του μοναδιαίου
# τετραγώνου [k-1, k] × [j-1, j], που βρίσκεται εξ ολοκλήρου
# μέσα στον κύκλο. Άρα 4·n1 τετράγωνα (και στα τέσσερα τεταρτημόρια)
# καλύπτουν σχεδόν όλο το εμβαδόν π·w², και 4·n1 / w² ≈ π.
rho_w = 4*n1 / w**2

# Εκτύπωση της ακτίνας, της προσέγγισης και του απόλυτου σφάλματος.
print(f'w      ={w:8d}')
print(f'rho_w  ={rho_w:18.12f}')
print(f'Σφάλμα ={abs(math.pi - rho_w):18.12f}')
