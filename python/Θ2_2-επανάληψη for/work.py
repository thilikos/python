import math

# Υπολογισμός του π με τη σειρά Leibniz:
#   π/4 = 1 - 1/3 + 1/5 - 1/7 + ... = Σ_{k≥1} (-1)^(k+1) / (2k-1).
# Για n = 10, 100, ..., 10^6 υπολογίζουμε το μερικό άθροισμα
# των n πρώτων όρων και συγκρίνουμε την προσέγγιση με το π.

for i in range(1, 7):
    n = 10**i                      # πλήθος όρων της σειράς
    print(f'n = {n}')

    e = 0                          # μερικό άθροισμα (προσέγγιση του π/4)
    for k in range(1, n + 1):
        # Ο k-οστός όρος: εναλλασσόμενο πρόσημο (+, -, +, ...)
        # και παρονομαστής ο k-οστός περιττός αριθμός 2k-1.
        y = (-1)**(k+1) / (2*k - 1)
        e = e + y

    appi = 4 * e                   # προσέγγιση του π

    # Εκτύπωση με 10 δεκαδικά ψηφία: προσέγγιση, π, σφάλμα.
    print(f'{appi:13.10f}, {math.pi:13.10f}, {math.pi - appi:13.10f} ')
