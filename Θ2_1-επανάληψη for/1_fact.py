# fact.py -- παραγοντικὸ μὲ βρόχο for
# Ὑπολογίζει τὸ n! = 1 · 2 · 3 · ... · n.

# Διαβάζουμε τὸν ἀκέραιο n ἀπὸ τὸν χρήστη.
n = int(input('Δῶσε ἕναν ἀκέραιο: '))

# Τὸ f κρατᾶ τὸ γινόμενο ποὺ ἔχει ὑπολογιστεῖ ὡς τώρα.
# Ἀρχικὴ τιμὴ 1, τὸ οὐδέτερο στοιχεῖο τοῦ πολλαπλασιασμοῦ,
# ὁπότε γιὰ n = 0 προκύπτει σωστὰ 0! = 1.
f = 1

# Πολλαπλασιάζουμε τὸ f διαδοχικὰ μὲ 1, 2, ..., n.
# Μετὰ τὸ βῆμα i ἰσχύει f = i!.
for i in range(1, n + 1):
    f *= i          # συντομογραφία τοῦ f = f * i

# Ἐκτύπωση τοῦ ἀποτελέσματος.
print('Τὸ παραγοντικὸ τοῦ', n, 'εἶναι τὸ', f)
