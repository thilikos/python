# Ἔλεγχος ἂν ἕνας ἀκέραιος εἶναι πρῶτος, μὲ δοκιμαστικὲς διαιρέσεις.

# Διαβάζουμε ἀπὸ τὸν χρήστη ἕναν ἀριθμὸ (ὡς κείμενο) καὶ τὸν
# μετατρέπουμε σὲ ἀκέραιο.
z = int(input("Δῶσε μου ἕναν ἀριθμό: "))

# Ὑποθέτουμε ἀρχικὰ ὅτι ὁ z εἶναι πρῶτος, μέχρι νὰ βρεθεῖ διαιρέτης.
isprime = True

# Δοκιμάζουμε κάθε πιθανὸ διαιρέτη i ἀπὸ τὸ 2 ἕως τὸ z-1.
for i in range(2, z):
    # Ἂν τὸ i διαιρεῖ ἀκριβῶς τὸν z (μηδενικὸ ὑπόλοιπο),
    # τότε ὁ z ἔχει γνήσιο διαιρέτη καὶ δὲν εἶναι πρῶτος.
    if z % i == 0:
        isprime = False

# Ἐπιλέγουμε τὴ λέξη ἄρνησης ἀνάλογα μὲ τὸ ἀποτέλεσμα
# (ὑπὸ συνθήκη ἔκφραση: τιμή_ἄν_ἀληθές if συνθήκη else τιμή_ἄν_ψευδές).
x = '' if isprime else 'δὲν'

# Ἐκτύπωση τοῦ ἀποτελέσματος.
print('Ὁ ἀριθμὸς', z, x, 'εἶναι πρῶτος')
