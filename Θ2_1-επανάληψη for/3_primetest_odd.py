# Ἔλεγχος ἂν ἕνας ἀκέραιος εἶναι πρῶτος. Βελτίωση τῆς προηγούμενης
# ἐκδοχῆς: χειριζόμαστε χωριστὰ τὸ 2 καὶ τοὺς ἄρτιους, καὶ
# δοκιμάζουμε μόνο περιττοὺς διαιρέτες.

# Διαβάζουμε τὸν ἀριθμὸ ἀπὸ τὸν χρήστη καὶ τὸν μετατρέπουμε σὲ ἀκέραιο.
z = int(input("Δῶσε μου ἕναν ἀριθμό: "))

# Ὑποθέτουμε ἀρχικὰ ὅτι ὁ z εἶναι πρῶτος.
isprime = True

# Τὸ 2 εἶναι πρῶτος, ἄρα δὲν χρειάζεται κανένας ἔλεγχος.
if z != 2:
    if z % 2 != 0:
        # Ὁ z εἶναι περιττός, ἄρα δὲν ἔχει ἄρτιους διαιρέτες.
        # Δοκιμάζουμε μόνο τοὺς περιττοὺς i = 3, 5, 7, ..., < z.
        for i in range(3, z, 2):
            if z % i == 0:
                # Βρέθηκε γνήσιος διαιρέτης: ὁ z δὲν εἶναι πρῶτος.
                isprime = False
    else:
        # Ὁ z εἶναι ἄρτιος καὶ διάφορος τοῦ 2,
        # ἄρα διαιρεῖται ἀπὸ τὸ 2 καὶ δὲν εἶναι πρῶτος.
        isprime = False

# Ἐκτύπωση τοῦ ἀποτελέσματος (True ἢ False).
print(isprime)
