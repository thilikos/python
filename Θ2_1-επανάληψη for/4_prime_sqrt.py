import math, time

# Ἐκτύπωση ὅλων τῶν πρώτων ἀριθμῶν ἕως τὸ 10000 μὲ δοκιμαστικὲς
# διαιρέσεις ἕως τὴν τετραγωνικὴ ῥίζα, καὶ μέτρηση τοῦ χρόνου.


# Ἐξετάζουμε μόνο τοὺς περιττοὺς n = 3, 5, 7, ..., 9999.
for n in range(3, 100000001, 2):
    a = True                 # ὑποθέτουμε ὅτι ὁ n εἶναι πρῶτος                     
    for k in range(3, math.ceil(math.sqrt(n)) + 1, 2):
        if n % k == 0:
            a = False                # βρέθηκε γνήσιος διαιρέτης
    if a :
        print(n, end=' ')










