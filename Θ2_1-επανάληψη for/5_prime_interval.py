# Ἔλεγχος ἂν κάθε ἀριθμὸς σὲ ἕνα διάστημα εἶναι πρῶτος.
# Ἐξετάζουμε τοὺς ἀκεραίους ἀπὸ 1.000.000 ἕως 1.099.999
# (τὸ range δὲν περιλαμβάνει τὸ ἄνω ἄκρο).

for z in range(1_000_000, 1_100_000):
    # Γιὰ κάθε z ὑποθέτουμε ἀρχικὰ ὅτι εἶναι πρῶτος.
    isprime = True

    if z % 2 == 0:
        # Ὁ z εἶναι ἄρτιος καὶ μεγαλύτερος τοῦ 2, ἄρα δὲν εἶναι πρῶτος.
        # Τυπώνουμε not isprime, δηλαδὴ False.
        print(z, not isprime)
    else:
        # Ὁ z εἶναι περιττός: δοκιμάζουμε μόνο περιττοὺς διαιρέτες
        # i = 3, 5, 7, ..., ἕως z // 2. Κανένας γνήσιος διαιρέτης
        # δὲν ὑπερβαίνει τὸ z/2.
        for i in range(3, z // 2 + 1, 2):
            if z % i == 0:
                # Βρέθηκε διαιρέτης: ὁ z δὲν εἶναι πρῶτος.
                isprime = False
        # Τυπώνουμε τὸν ἀριθμὸ καὶ τὸ ἀποτέλεσμα (True ἢ False).
        print(z, isprime)
