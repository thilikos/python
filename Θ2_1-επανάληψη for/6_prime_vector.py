import math
import matplotlib.pyplot as plt

# Βρίσκουμε τοὺς πρώτους ἕως n καὶ σχεδιάζουμε
# τὴ γραφικὴ παράσταση «α/α πρώτου → πρῶτος».

n = 40000
y = [2]                          # τὸ 2 εἶναι ὁ μόνος ἄρτιος πρῶτος

# Ἐξετάζουμε τοὺς περιττοὺς c = 3, 5, ..., n.
for c in range(3, n + 1, 2):
    flag = 1                     # σημαία: 1 = «πρῶτος», 0 = «σύνθετος»

    # Δοκιμαστικὲς διαιρέσεις μόνο μὲ περιττοὺς k = 3, 5, ..., ⌊√c⌋,
    # ἀφοῦ ὁ c εἶναι περιττός.
    for k in range(3, math.isqrt(c) + 1, 2):
        if c % k == 0:
            flag = 0             # βρέθηκε διαιρέτης
            break                # δὲν χρειάζεται νὰ συνεχίσουμε

    if flag:
        y.append(c)              # ὁ c εἶναι πρῶτος· τὸν κρατᾶμε

# Οἱ τετμημένες: ὁ αὔξων ἀριθμὸς κάθε πρώτου (1, 2, ..., l),
# ὥστε y[i-1] νὰ εἶναι ὁ i-οστὸς πρῶτος.
l = len(y)
x = list(range(1, l + 1))
print(f'Πλῆθος πρώτων ≤ {n}: {l}')

# Γραφικὴ παράσταση: στὸ σημεῖο i ὁ i-οστὸς πρῶτος.
plt.plot(x, y)
plt.show()
