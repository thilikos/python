import random

import matplotlib.pyplot as plt

# Νέφος 10000 σημείων μὲ κανονικὴ κατανομὴ στὶς δύο συντεταγμένες.
# Οἱ συντεταγμένες x καὶ y εἶναι ἀνεξάρτητες, ἄρα τὸ νέφος εἶναι
# κυκλικὰ συμμετρικὸ γύρω ἀπὸ τὸ κέντρο του.

x = []      # οἱ τετμημένες τῶν σημείων
y = []      # οἱ τεταγμένες τῶν σημείων
for i in range(100000):
    # random.normalvariate(1, 1): κανονικὴ κατανομὴ μὲ μέση τιμὴ 1
    # καὶ τυπικὴ ἀπόκλιση 1. Ὁ πολλαπλασιασμὸς ἐπὶ 100 δίνει
    # κανονικὴ κατανομὴ μὲ μέση τιμὴ 100 καὶ τυπικὴ ἀπόκλιση 100.
    x.append(100 * random.normalvariate(1, .1))
    y.append(100 * random.normalvariate(1, .1))

# Ἐκτύπωση τῶν δύο λιστῶν καὶ τοῦ πλήθους τῶν σημείων
# (προσοχή: τυπώνονται 20000 ἀριθμοί)
print(x, y, len(x))

# Σχεδίαση: κάθε σημεῖο (x[i], y[i]) ὡς τελεία, χωρὶς γραμμές
plt.plot(x, y, ".")
plt.show()
