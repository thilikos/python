import math

# Ὑπολογισμὸς τοῦ π μὲ τὴ σειρὰ Leibniz:
#   π/4 = 1 - 1/3 + 1/5 - 1/7 + ... = Σ_{k≥1} (-1)^(k+1) / (2k-1).
# Γιὰ n = 10, 100, ..., 10^6 ὑπολογίζουμε τὸ μερικὸ ἄθροισμα
# τῶν n πρώτων ὅρων καὶ συγκρίνουμε τὴν προσέγγιση μὲ τὸ π.

for i in range(1, 7):
    n = 10**i                      # πλῆθος ὅρων τῆς σειρᾶς
    print(f'n = {n}')

    e = 0                          # μερικὸ ἄθροισμα (προσέγγιση τοῦ π/4)
    for k in range(1, n + 1):
        # Ὁ k-οστὸς ὅρος: ἐναλλασσόμενο πρόσημο (+, -, +, ...)
        # καὶ παρονομαστὴς ὁ k-οστὸς περιττὸς ἀριθμὸς 2k-1.
        y = (-1)**(k+1) / (2*k - 1)
        e = e + y

    appi = 4 * e                   # προσέγγιση τοῦ π

    # Ἐκτύπωση μὲ 10 δεκαδικὰ ψηφία: προσέγγιση, π, σφάλμα.
    print(f'{appi:13.10f}, {math.pi:13.10f}, {math.pi - appi:13.10f} ')
