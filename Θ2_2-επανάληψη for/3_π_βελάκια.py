import random

# Προσέγγιση τοῦ π μὲ τὴ μέθοδο Monte Carlo:
# ῥίχνουμε n βελάκια στὸ τετράγωνο [-1, 1] x [-1, 1] καὶ μετρᾶμε
# πόσα πέφτουν μέσα στὸν ἐγγεγραμμένο κύκλο ἀκτίνας 1.
# Ὁ λόγος τῶν ἐμβαδῶν κύκλου καὶ τετραγώνου εἶναι π·1² / 2² = π/4,
# ἄρα ἡ πιθανότητα ἕνα βελάκι νὰ πέσει στὸν κύκλο εἶναι π/4.

n = 1000000      # πλῆθος ῥίψεων
hits = 0         # πλῆθος ἐπιτυχιῶν (βελάκια μέσα στὸν κύκλο)
for i in range(n):
    # ῥίχνω τὸ βελάκι i: τυχαῖο σημεῖο (x, y), ὁμοιόμορφα στὸ τετράγωνο
    x = random.uniform(-1, 1)
    y = random.uniform(-1, 1)
    # ἐλέγχω ἂν εἶναι ἐπιτυχία: τὸ σημεῖο ἀπέχει ἀπὸ τὸ (0, 0)
    # ἀπόσταση τὸ πολὺ 1 (συγκρίνουμε τετράγωνα, χωρὶς ῥίζα)
    if x**2 + y**2 <= 1:
        hits += 1

# Ἡ σχετικὴ συχνότητα hits/n προσεγγίζει τὸ π/4,
# ὁπότε τὸ 4·hits/n προσεγγίζει τὸ π.
my_pi = 4 * hits / n
print(my_pi)
