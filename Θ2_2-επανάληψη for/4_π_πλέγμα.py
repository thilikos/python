import math

# Προσέγγιση τοῦ π μὲ μέτρηση σημείων πλέγματος (ἀκέραιων σημείων)
# μέσα σὲ κύκλο ἀκτίνας w μὲ κέντρο τὴν ἀρχὴ τῶν ἀξόνων.
# Μετρᾶμε τὰ σημεῖα (k, j) μὲ k, j ≥ 1 καὶ k² + j² ≤ w²,
# δηλαδὴ τὰ σημεῖα τοῦ πρώτου τεταρτημορίου ἐκτὸς τῶν ἀξόνων.

w = int(input('Ἀκτίνα κύκλου: '))

n1 = 0                           # πλῆθος σημείων στὸ πρῶτο τεταρτημόριο
for k in range(1, w + 1):
    # Γιὰ σταθερὴ τετμημένη k, οἱ ἐπιτρεπτὲς τεταγμένες j ≥ 1 εἶναι
    # αὐτὲς μὲ j ≤ √(w² - k²), δηλαδὴ m = ⌊√(w² - k²)⌋ τὸ πλῆθος.
    m = math.floor(math.sqrt(w**2 - k**2))
    n1 = n1 + m

# Κάθε σημεῖο (k, j) εἶναι ἡ πάνω δεξιὰ κορυφὴ τοῦ μοναδιαίου
# τετραγώνου [k-1, k] × [j-1, j], ποὺ βρίσκεται ἐξ ὁλοκλήρου
# μέσα στὸν κύκλο. Ἄρα 4·n1 τετράγωνα (καὶ στὰ τέσσερα τεταρτημόρια)
# καλύπτουν σχεδὸν ὅλο τὸ ἐμβαδὸν π·w², καὶ 4·n1 / w² ≈ π.
rho_w = 4*n1 / w**2

# Ἐκτύπωση τῆς ἀκτίνας, τῆς προσέγγισης καὶ τοῦ ἀπόλυτου σφάλματος.
print(f'w      ={w:8d}')
print(f'rho_w  ={rho_w:18.12f}')
print(f'Σφάλμα ={abs(math.pi - rho_w):18.12f}')
