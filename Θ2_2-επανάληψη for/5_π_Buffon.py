import math, random

# Προσομοίωση τοῦ προβλήματος τῆς βελόνας τοῦ Buffon:
# ῥίχνουμε τυχαῖα μιὰ βελόνα μήκους 1 σὲ ἐπίπεδο μὲ παράλληλες
# ὁριζόντιες εὐθεῖες σὲ ἀπόσταση 1 (τὶς εὐθεῖες y = ἀκέραιος).
# Ἡ πιθανότητα ἡ βελόνα νὰ τέμνει κάποια εὐθεία εἶναι 2/π,
# ὁπότε ἀπὸ τὴ σχετικὴ συχνότητα τομῶν ἐκτιμοῦμε τὸ π.

drops = 1000000
# φορὲς ῥίψης
success = 0      # πλῆθος ῥίψεων στὶς ὁποῖες ἡ βελόνα τέμνει εὐθεία

for i in range(1, drops + 1):
    # Τὸ ὕψος τοῦ ἑνὸς ἄκρου τῆς βελόνας, ὁμοιόμορφα στὸ [0, 1).
    # Λόγω περιοδικότητας ἀρκεῖ νὰ ἐξετάσουμε μία μόνο λωρίδα.
    y = random.random()

    # Ἡ γωνία τῆς βελόνας ὡς πρὸς τὶς εὐθεῖες, ὁμοιόμορφα στὸ [0, 2π).
    a = random.random() * 2 * math.pi

    # Τὸ ὕψος τοῦ ἄλλου ἄκρου (ἡ βελόνα ἔχει μῆκος 1).
    # Μᾶς ἐνδιαφέρει μόνο ἡ κατακόρυφη συνιστῶσα sin(a).
    y1 = y + math.sin(a)

    # Ἡ βελόνα τέμνει εὐθεία ἀκριβῶς ὅταν ὑπάρχει ἀκέραιος στὸ
    # διάστημα [min(y, y1), max(y, y1)]. Ἀφοῦ τὸ διάστημα ἔχει μῆκος
    # τὸ πολὺ 1, αὐτὸ ἰσοδυναμεῖ μὲ floor(max) == ceil(min).
    # Ἡ Python μετατρέπει τὸ True/False σὲ 1/0 κατὰ τὴν πρόσθεση.
    success = success + (math.floor(max(y, y1)) == math.ceil(min(y, y1)))

# Ἀπὸ success/drops ≈ 2/π προκύπτει π ≈ 2·drops/success.
mypi = 2*drops / success

print(f'mypi = {mypi}')        # ἡ ἐκτίμηση τοῦ π
print(f'pi = {math.pi}')       # ἡ πραγματικὴ τιμή
print(f'{math.pi - mypi}')     # τὸ σφάλμα τῆς ἐκτίμησης
