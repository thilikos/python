# Λίστες: οἱ βασικοὶ ὁρισμοί
#
# Μιὰ λίστα (list) εἶναι μιὰ ΔΙΑΤΕΤΑΓΜΕΝΗ συλλογὴ τιμῶν μὲ ἕνα κοινὸ ὄνομα.
# Κάθε στοιχεῖο ἔχει μιὰ θέση, τὸν δείκτη (index), ποὺ ξεκινᾶ ἀπὸ τὸ 0.
# Τὸ μέγεθος μιᾶς λίστας ἀλλάζει κατὰ τὴν ἐκτέλεση (προσθέτουμε / ἀφαιροῦμε).

# ---------------------------------------------------------------- 1. Δημιουργία
a = [5, 10, 15, 20, 25]           # ῥητὴ ἀπαρίθμηση
b = [10, 'Γειά', 2.5, True]       # μπορεῖ νὰ ἔχει διαφορετικοὺς τύπους
c = [0] * 5                       # ἐπανάληψη: [0, 0, 0, 0, 0]
d = list(range(0, 11, 2))         # ἀπὸ range: [0, 2, 4, 6, 8, 10]

e = []                            # κενὴ λίστα ...
for i in range(1, 6):
    e.append(i**2)                # ... ποὺ τὴ γεμίζουμε σταδιακὰ μὲ append

f = [i**2 for i in range(1, 6)]   # τὸ ἴδιο, μὲ λίστα κατανόησης (list comprehension)

print('a =', a)
print('b =', b)
print('c =', c)
print('d =', d)
print('e =', e)
print('f =', f)
print()

# ------------------------------------------------ 2. Μῆκος καὶ δεῖκτες (indices)
print('len(a) =', len(a))
print('a[0] =', a[0], '  a[4] =', a[4])
print('a[-1] =', a[-1], '  a[-2] =', a[-2], '  (ἀρνητικοὶ δεῖκτες: ἀπὸ τὸ τέλος)')
# print(a[5])                     # IndexError: δὲν ὑπάρχει θέση 5
print()

# ------------------------------- 3. Τεμαχισμὸς (slicing): λίστα[ἀρχή:τέλος:βῆμα]
# Τὸ στοιχεῖο στὴ θέση "τέλος" ΔΕΝ περιλαμβάνεται (ὅπως στὸ range).
L = [10, 20, 30, 40, 50, 60, 70, 80]
print('L[2:5]   =', L[2:5])
print('L[:3]    =', L[:3])
print('L[4:]    =', L[4:])
print('L[1:7:2] =', L[1:7:2])
print('L[::-1]  =', L[::-1], '  (ἀντιστροφή)')
print()

# ------------------------------------------- 4. Ἀλλαγὴ στοιχείων καὶ μέθοδοι
nums = [3, 1, 4, 1, 5]
nums[0] = 30                      # οἱ λίστες εἶναι μεταβλητὲς (mutable)
nums.append(9)                    # προσθήκη στὸ τέλος
nums.insert(1, 2)                 # εἰσαγωγὴ στὴ θέση 1
last = nums.pop()                 # ἀφαιρεῖ καὶ ἐπιστρέφει τὸ τελευταῖο
nums.remove(1)                    # ἀφαιρεῖ τὴν ΠΡΩΤΗ ἐμφάνιση τοῦ 1
print('nums =', nums, '   pop() ἔδωσε', last)
print('4 in nums :', 4 in nums)
print('πλῆθος 1  :', nums.count(1))
print('θέση τοῦ 5:', nums.index(5))
print('min =', min(nums), ' max =', max(nums), ' sum =', sum(nums))
nums.sort()
print('ταξινομημένη:', nums)
print('συνένωση [1, 2] + [3, 4] =', [1, 2] + [3, 4])
print()

# ----------------------------------------------------------------- 5. Διάσχιση
values = [2, -4, 6, -8, 10]

for x in values:                  # ὅταν μᾶς ἐνδιαφέρουν μόνο οἱ τιμές
    print(x, end=' ')
print()

for i in range(len(values)):      # ὅταν μᾶς ἐνδιαφέρει καὶ ἡ θέση
    print(f'values[{i}] = {values[i]}')

for i, x in enumerate(values):    # τὸ ἴδιο, πιὸ κομψά
    print(i, x, end=' | ')
print()

xs = [0, 1, 2, 3]
ys = [0, 1, 4, 9]
for x, y in zip(xs, ys):          # δύο λίστες "παράλληλα": ζεύγη (x, y)
    print(f'({x}, {y})', end=' ')
print('\n')

# -------------------------------- 6. ΠΡΟΣΟΧΗ: ἡ ἐκχώρηση ΔΕΝ φτιάχνει ἀντίγραφο
list_a = [1, 2, 3]
list_b = list_a                   # ἡ ΙΔΙΑ λίστα μὲ δεύτερο ὄνομα
list_c = list_a[:]                # πραγματικὸ ἀντίγραφο (ἢ list(list_a))
list_a[0] = 99
print('list_a =', list_a)
print('list_b =', list_b, '  <- ἄλλαξε κι αὐτή!')
print('list_c =', list_c, '  <- ἔμεινε ἴδια')
print('list_a is list_b:', list_a is list_b, '   list_a is list_c:', list_a is list_c)


# Τὸ ἴδιο συμβαίνει ὅταν δίνουμε μιὰ λίστα σὲ συνάρτηση:
def add_zero(v):
    v.append(0)                   # ἀλλάζει τὴν ΙΔΙΑ λίστα ποὺ μᾶς ἔδωσαν


w = [1, 2]
add_zero(w)
print('w μετὰ τὴν add_zero(w):', w)
print()

# ------------------------------------------ 7. Πλειάδες (tuples): "σταθερὲς λίστες"
p = (3, -2)                       # δὲν ἀλλάζει: p[0] = 5 δίνει TypeError
x, y = p                          # ξεπακετάρισμα (unpacking)
print('p =', p, '  x =', x, '  y =', y)


def min_max(v):
    return min(v), max(v)         # μιὰ συνάρτηση ποὺ ἐπιστρέφει ΔΥΟ τιμές = πλειάδα


lo, hi = min_max([4, 8, 1, 7])
print('min =', lo, '  max =', hi)
