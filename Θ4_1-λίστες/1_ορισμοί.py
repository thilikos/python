# Λίστες: οι βασικοί ορισμοί
#
# Μια λίστα (list) είναι μια ΔΙΑΤΕΤΑΓΜΕΝΗ συλλογή τιμών με ένα κοινό όνομα.
# Κάθε στοιχείο έχει μια θέση, τον δείκτη (index), που ξεκινά από το 0.
# Το μέγεθος μιας λίστας αλλάζει κατά την εκτέλεση (προσθέτουμε / αφαιρούμε).

# ---------------------------------------------------------------- 1. Δημιουργία
a = [5, 10, 15, 20, 25]           # ρητή απαρίθμηση
b = [10, 'Γεια', 2.5, True]       # μπορεί να έχει διαφορετικούς τύπους
c = [0] * 5                       # επανάληψη: [0, 0, 0, 0, 0]
d = list(range(0, 11, 2))         # από range: [0, 2, 4, 6, 8, 10]

e = []                            # κενή λίστα ...
for i in range(1, 6):
    e.append(i**2)                # ... που τη γεμίζουμε σταδιακά με append

f = [i**2 for i in range(1, 6)]   # το ίδιο, με λίστα κατανόησης (list comprehension)

print('a =', a)
print('b =', b)
print('c =', c)
print('d =', d)
print('e =', e)
print('f =', f)
print()

# ------------------------------------------------ 2. Μήκος και δείκτες (indices)
print('len(a) =', len(a))
print('a[0] =', a[0], '  a[4] =', a[4])
print('a[-1] =', a[-1], '  a[-2] =', a[-2], '  (αρνητικοί δείκτες: από το τέλος)')
# print(a[5])                     # IndexError: δεν υπάρχει θέση 5
print()

# ------------------------------- 3. Τεμαχισμός (slicing): λίστα[αρχή:τέλος:βήμα]
# Το στοιχείο στη θέση "τέλος" ΔΕΝ περιλαμβάνεται (όπως στο range).
L = [10, 20, 30, 40, 50, 60, 70, 80]
print('L[2:5]   =', L[2:5])
print('L[:3]    =', L[:3])
print('L[4:]    =', L[4:])
print('L[1:7:2] =', L[1:7:2])
print('L[::-1]  =', L[::-1], '  (αντιστροφή)')
print()

# ------------------------------------------- 4. Αλλαγή στοιχείων και μέθοδοι
nums = [3, 1, 4, 1, 5]
nums[0] = 30                      # οι λίστες είναι μεταβλητές (mutable)
nums.append(9)                    # προσθήκη στο τέλος
nums.insert(1, 2)                 # εισαγωγή στη θέση 1
last = nums.pop()                 # αφαιρεί και επιστρέφει το τελευταίο
nums.remove(1)                    # αφαιρεί την ΠΡΩΤΗ εμφάνιση του 1
print('nums =', nums, '   pop() έδωσε', last)
print('4 in nums :', 4 in nums)
print('πλήθος 1  :', nums.count(1))
print('θέση του 5:', nums.index(5))
print('min =', min(nums), ' max =', max(nums), ' sum =', sum(nums))
nums.sort()
print('ταξινομημένη:', nums)
print('συνένωση [1, 2] + [3, 4] =', [1, 2] + [3, 4])
print()

# ----------------------------------------------------------------- 5. Διάσχιση
values = [2, -4, 6, -8, 10]

for x in values:                  # όταν μας ενδιαφέρουν μόνο οι τιμές
    print(x, end=' ')
print()

for i in range(len(values)):      # όταν μας ενδιαφέρει και η θέση
    print(f'values[{i}] = {values[i]}')

for i, x in enumerate(values):    # το ίδιο, πιο κομψά
    print(i, x, end=' | ')
print()

xs = [0, 1, 2, 3]
ys = [0, 1, 4, 9]
for x, y in zip(xs, ys):          # δύο λίστες "παράλληλα": ζεύγη (x, y)
    print(f'({x}, {y})', end=' ')
print('\n')

# -------------------------------- 6. ΠΡΟΣΟΧΗ: η εκχώρηση ΔΕΝ φτιάχνει αντίγραφο
list_a = [1, 2, 3]
list_b = list_a                   # η ΙΔΙΑ λίστα με δεύτερο όνομα
list_c = list_a[:]                # πραγματικό αντίγραφο (ή list(list_a))
list_a[0] = 99
print('list_a =', list_a)
print('list_b =', list_b, '  <- άλλαξε κι αυτή!')
print('list_c =', list_c, '  <- έμεινε ίδια')
print('list_a is list_b:', list_a is list_b, '   list_a is list_c:', list_a is list_c)


# Το ίδιο συμβαίνει όταν δίνουμε μια λίστα σε συνάρτηση:
def add_zero(v):
    v.append(0)                   # αλλάζει την ΙΔΙΑ λίστα που μας έδωσαν


w = [1, 2]
add_zero(w)
print('w μετά την add_zero(w):', w)
print()

# ------------------------------------------ 7. Πλειάδες (tuples): "σταθερές λίστες"
p = (3, -2)                       # δεν αλλάζει: p[0] = 5 δίνει TypeError
x, y = p                          # ξεπακετάρισμα (unpacking)
print('p =', p, '  x =', x, '  y =', y)


def min_max(v):
    return min(v), max(v)         # μια συνάρτηση που επιστρέφει ΔΥΟ τιμές = πλειάδα


lo, hi = min_max([4, 8, 1, 7])
print('min =', lo, '  max =', hi)
