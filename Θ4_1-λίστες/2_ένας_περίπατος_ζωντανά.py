import matplotlib.pyplot as plt

import my_random_walk as myrw

# Ἕνας τυχαῖος περίπατος στὸ πλέγμα, σχεδιασμένος "ζωντανά".
# Ὅπως τὸ 2_ένας_περίπατος.py, ἀλλὰ ἡ διαδρομὴ ἐμφανίζεται βῆμα-βῆμα:
# στὸ βῆμα k σχεδιάζουμε τὶς θέσεις 0, 1, ..., k, δηλαδὴ τὰ κομμάτια
# sx[:k+1] καὶ sy[:k+1] τῶν λιστῶν.

n = 100
sx, sy = myrw.random_walk(n)


steps = len(sx) - 1               # ἡ λίστα περιέχει καὶ τὴν ἀρχικὴ θέση
print(f'Βήματα μέχρι τὴν ἄκρη: {steps}')
print('Οἱ 10 πρῶτες θέσεις :', list(zip(sx[:100], sy[:100])))
print('Ἡ τελευταία θέση    :', (sx[-1], sy[-1]))
print('Μεγαλύτερο / μικρότερο x:', max(sx), min(sx))
print('Μεγαλύτερο / μικρότερο y:', max(sy), min(sy))

# Γιὰ μεγάλο n ὁ περίπατος ἔχει δεκάδες χιλιάδες βήματα. Ἀντὶ νὰ ξανασχεδιάζουμε
# μετὰ ἀπὸ κάθε βῆμα, ξανασχεδιάζουμε κάθε 'every' βήματα, ὥστε ὅλο τὸ σχέδιο
# νὰ γίνει σὲ περίπου 'frames' καρέ, ὅποιο κι ἂν εἶναι τὸ n.
frames = 400                      # πόσα καρὲ θέλουμε (περισσότερα = πιὸ ἀργά)
delay = 0.001                      # δευτερόλεπτα ἀνὰ καρέ
every = max(1, steps // frames)   # βήματα ἀνὰ καρὲ (1 γιὰ μικρὰ n)

fig, ax = plt.subplots()
ax.plot([-n, -n, n, n, -n], [-n, n, n, -n, -n], 'r')   # τὸ τετράγωνο
ax.set_xlim(-1.1 * n, 1.1 * n)    # σταθεροὶ ἄξονες, γιὰ νὰ μὴ "χορεύει" ἡ εἰκόνα
ax.set_ylim(-1.1 * n, 1.1 * n)
ax.set_aspect('equal')

# Τὸ plot ἐπιστρέφει λίστα μὲ μία γραμμή: τὴν "ξεπακετάρουμε" μὲ τὸ κόμμα.
path, = ax.plot([], [], 'b', lw=0.8)                   # ἡ διαδρομή, ἄδεια στὴν ἀρχή
ax.plot(sx[0], sy[0], 'go')                            # ἀρχὴ (πάνω ἀπὸ τὴ διαδρομή)
here, = ax.plot([], [], 'ro')                          # ἡ τρέχουσα θέση

# Τὰ βήματα 0, every, 2*every, ... καί, στὸ τέλος, τὸ τελευταῖο βῆμα.
for k in list(range(0, steps, every)) + [steps]:
    if not plt.fignum_exists(fig.number):   # κλείσαμε τὸ παράθυρο: σταματᾶμε
        break
    path.set_data(sx[:k + 1], sy[:k + 1])
    here.set_data([sx[k]], [sy[k]])
    ax.set_title(f'Τυχαῖος περίπατος: n = {n}, βῆμα {k} ἀπὸ {steps}')
    plt.pause(delay)

plt.show()
