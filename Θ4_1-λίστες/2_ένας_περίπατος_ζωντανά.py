import matplotlib.pyplot as plt

import my_random_walk as myrw

# Ένας τυχαίος περίπατος στο πλέγμα, σχεδιασμένος "ζωντανά".
# Όπως το 2_ένας_περίπατος.py, αλλά η διαδρομή εμφανίζεται βήμα-βήμα:
# στο βήμα k σχεδιάζουμε τις θέσεις 0, 1, ..., k, δηλαδή τα κομμάτια
# sx[:k+1] και sy[:k+1] των λιστών.

n = 100
sx, sy = myrw.random_walk(n)


steps = len(sx) - 1               # η λίστα περιέχει και την αρχική θέση
print(f'Βήματα μέχρι την άκρη: {steps}')
print('Οι 10 πρώτες θέσεις :', list(zip(sx[:100], sy[:100])))
print('Η τελευταία θέση    :', (sx[-1], sy[-1]))
print('Μεγαλύτερο / μικρότερο x:', max(sx), min(sx))
print('Μεγαλύτερο / μικρότερο y:', max(sy), min(sy))

# Για μεγάλο n ο περίπατος έχει δεκάδες χιλιάδες βήματα. Αντί να ξανασχεδιάζουμε
# μετά από κάθε βήμα, ξανασχεδιάζουμε κάθε 'every' βήματα, ώστε όλο το σχέδιο
# να γίνει σε περίπου 'frames' καρέ, όποιο κι αν είναι το n.
frames = 400                      # πόσα καρέ θέλουμε (περισσότερα = πιο αργά)
delay = 0.001                      # δευτερόλεπτα ανά καρέ
every = max(1, steps // frames)   # βήματα ανά καρέ (1 για μικρά n)

fig, ax = plt.subplots()
ax.plot([-n, -n, n, n, -n], [-n, n, n, -n, -n], 'r')   # το τετράγωνο
ax.set_xlim(-1.1 * n, 1.1 * n)    # σταθεροί άξονες, για να μη "χορεύει" η εικόνα
ax.set_ylim(-1.1 * n, 1.1 * n)
ax.set_aspect('equal')

# Το plot επιστρέφει λίστα με μία γραμμή: την "ξεπακετάρουμε" με το κόμμα.
path, = ax.plot([], [], 'b', lw=0.8)                   # η διαδρομή, άδεια στην αρχή
ax.plot(sx[0], sy[0], 'go')                            # αρχή (πάνω από τη διαδρομή)
here, = ax.plot([], [], 'ro')                          # η τρέχουσα θέση

# Τα βήματα 0, every, 2*every, ... και, στο τέλος, το τελευταίο βήμα.
for k in list(range(0, steps, every)) + [steps]:
    if not plt.fignum_exists(fig.number):   # κλείσαμε το παράθυρο: σταματάμε
        break
    path.set_data(sx[:k + 1], sy[:k + 1])
    here.set_data([sx[k]], [sy[k]])
    ax.set_title(f'Τυχαίος περίπατος: n = {n}, βήμα {k} από {steps}')
    plt.pause(delay)

plt.show()
