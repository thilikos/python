# Ἡ θερμοκρασία σὲ κάθε σημεῖο τοῦ πλέγματος ἀποθηκεύεται σὲ ἕναν πίνακα
# (λίστα ἀπὸ λίστες). Σὲ κάθε βῆμα, κάθε ἐσωτερικὸ σημεῖο παίρνει τὸν μέσο
# ὅρο τοῦ ἑαυτοῦ του καὶ τῶν 8 γειτόνων του. Τὸ περίγραμμα μένει 0 ("κρύο"),
# ὁπότε ἡ θερμότητα σιγὰ-σιγὰ ἁπλώνεται καὶ φεύγει ἀπὸ τὰ ἄκρα.


# ---------------------------------------- Ἀρχικὴ θερμοκρασία στὸ σημεῖο (x, y)
# Δοκιμάστε καὶ τὶς ἄλλες: βάλτε # μπροστὰ ἀπὸ τὴν ἐνεργὴ καὶ βγάλτε το ἀπὸ ἄλλη.
def funn(x, y):
    #return (100 * math.exp(-0.4 * ((x - 1)**2 + 0.7 * (y - 3)**2))+ 80 * math.exp(-0.2 * (2 * (x - 5)**2 + 1.5 * (y - 1)**2)))
    # return x**2 + y**2
    # return math.cos(x * y)
    # return 250 * random.random()
    # return math.cos(x) * math.cos(y)
    return math.cos(1 / x) * math.cos(1 / y)


# ------------------------------- Πίνακας n x n μὲ τὶς τιμὲς τῆς funn σὲ πλέγμα
# Τὸ πλέγμα καλύπτει τὸ τετράγωνο [a, b] x [a, b] μὲ n σημεῖα σὲ κάθε πλευρά,
# ποὺ ἀπέχουν μεταξύ τους h. Τὸ στοιχεῖο [i][j] εἶναι ἡ funn στὸ σημεῖο
#   x = a + j*h   (ἡ στήλη j δίνει τὸ x)
#   y = a + i*h   (ἡ γραμμὴ i δίνει τὸ y)
def ongrid(a, b, n):
    h = (b - a) / (n - 1)
    # Πίνακας n x n γεμάτος μηδενικά: n γραμμές, καθεμία ἡ λίστα [0, 0, ..., 0]
    # μὲ n μηδενικά. Τὸ "for i in range(n)" φτιάχνει κάθε φορὰ ΝΕΑ γραμμή.
    # (Τὸ [[0] * n] * n θὰ ἔβαζε n φορὲς τὴν ΙΔΙΑ γραμμή: λάθος!)
    values = [[0] * n for i in range(n)]
    for i in range(n):
        for j in range(n):
            x = a + j * h
            y = a + i * h
            values[i][j] = funn(x, y)
    return values


# ------------------------------------------------------ Ἕνα βῆμα θερμότητας
# Κάθε ἐσωτερικὸ στοιχεῖο γίνεται ὁ μέσος ὅρος τοῦ 3 x 3 τετραγώνου γύρω του.
# Τὰ στοιχεῖα τοῦ περιγράμματος (πρώτη/τελευταία γραμμὴ καὶ στήλη) γίνονται 0.
def average(A):
    m = len(A)
    n = len(A[0])
    B = [[0] * n for i in range(m)]
    for i in range(1, m - 1):
        for j in range(1, n - 1):
            B[i][j] = (A[i - 1][j - 1] + A[i - 1][j] + A[i - 1][j + 1] +
                       A[i][j - 1]     + A[i][j]     + A[i][j + 1] +
                       A[i + 1][j - 1] + A[i + 1][j] + A[i + 1][j + 1]) / 9
    return B


# ------------------------------------------------- Ζωγραφίζει τὸν πίνακα T
# Σβήνει τὸ προηγούμενο σχέδιο, ζωγραφίζει τὸν T μὲ χρώματα "φωτιᾶς" καὶ
# γράφει ἀπὸ πάνω τὸν ἀριθμὸ τοῦ βήματος tau.
def draw(T, tau):
    plt.clf()
    plt.pcolormesh(T, cmap='hot', shading='gouraud')
    plt.title(f'tau = {tau}', fontsize=14)
    plt.pause(0.001)



# =========================== 1. Ἡ funn ὡς "χάρτης θερμότητας"  (_1_pyars.m)
w = ongrid(-2, 8, 60)                             # 201 x 201 σημεῖα στὸ [-8, 8] x [-8, 8]
plt.pcolormesh(w, cmap='hot', shading='gouraud')   # colormap('hot'), pcolor, shading interp
plt.show()                                         # κλεῖστε τὸ παράθυρο γιὰ νὰ συνεχίσει


# ================================= 2. Ἡ θερμότητα ἁπλώνεται  (_2_smav.m)
T = ongrid(-2, 8, 60)                              # 60 x 60 σημεῖα στὸ [-2, 8] x [-2, 8]
steps = 200000

step = 10

for tau in range(steps + 1):
    if tau % step == 0:            # ζωγραφίζουμε κάθε step βήματα: τὸ σχέδιο εἶναι πολὺ πιὸ ἀργὸ ἀπὸ τὸ βῆμα
        draw(T, tau)
    T = average(T)
