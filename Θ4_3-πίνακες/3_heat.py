import math
import random                    # χρειάζεται μόνο γιὰ τὸ 250 * random.random() στὴ funn

import matplotlib.pyplot as plt

# Διάδοση θερμότητας σὲ ἕνα πλέγμα (μετατροπὴ τῶν ἀρχείων MATLAB τοῦ φακέλου).
